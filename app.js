// Cargar la última semana desde Firestore
async function loadLastWeekFromFirestore() {
  if (!db) {
    showToast('Firestore no está configurado. Conectá Firebase primero.');
    return;
  }
  
  const loading = document.getElementById('history-loading');
  const resultsDiv = document.getElementById('history-results');
  
  loading.style.display = 'block';
  resultsDiv.innerHTML = '';
  
  try {
    // Obtener todas las semanas disponibles desde Firestore
    const weeksSnapshot = await getDocs(collection(db, 'weeks'));
    if (weeksSnapshot.empty) {
      loading.style.display = 'none';
      resultsDiv.innerHTML = '<div class="no-data"><p>📭 No hay datos en Firestore aún.</p><p style="font-size:12px; margin-top:8px;">Comenzá a cargar medicación para los pacientes.</p></div>';
      return;
    }
    
    // Ordenar semanas por ID descendente (la más reciente primero)
    const weeks = [];
    weeksSnapshot.forEach(doc => {
      weeks.push({ id: doc.id, data: doc.data() });
    });
    weeks.sort((a, b) => b.id.localeCompare(a.id));

    // "Semana anterior" = semana inmediatamente anterior a la actual
    const lastWeekId = getPrevWeekId(currentWeek);
    const lastWeekDoc = weeks.find(w => w.id === lastWeekId);

    if (!lastWeekDoc) {
      loading.style.display = 'none';
      resultsDiv.innerHTML = `<div class="no-data"><p>📭 No hay datos para la semana anterior (${lastWeekId}).</p><p style="font-size:12px; margin-top:8px;">Cargá datos en esa semana para visualizar el historial.</p></div>`;
      return;
    }

    const lastWeekData = lastWeekDoc.data;
    
    loading.style.display = 'none';
    
    // Procesar y mostrar los datos
    const results = await processWeekData(lastWeekId, lastWeekData, { onlyDischarges: false });
    renderHistoryResults(results, `📅 Semana anterior con datos: ${lastWeekId} · ${getWeekDates(lastWeekId)}`);
    
  } catch (error) {
    console.error('Error loading last week:', error);
    loading.style.display = 'none';
    resultsDiv.innerHTML = `<div class="no-data"><p>❌ Error al cargar datos: ${error.message}</p></div>`;
    showToast('Error al consultar Firestore');
  }
}


async function getDischargesByHc() {
  const dischargesByHc = new Map();
  const dischargesSnapshot = await getDocs(collection(db, 'discharges'));

  dischargesSnapshot.forEach(dischargeDoc => {
    const discharge = dischargeDoc.data();
    if (!discharge?.hc) return;

    const hcKey = String(discharge.hc);
    const existing = dischargesByHc.get(hcKey);

    // Conservar el registro más reciente cuando hay duplicados por HC
    if (!existing || Number(discharge.timestamp || 0) > Number(existing.timestamp || 0)) {
      dischargesByHc.set(hcKey, discharge);
    }
  });

  return dischargesByHc;
}

// Procesar los datos de una semana - versión optimizada
async function processWeekData(weekId, weekData, options = {}) {
  const { onlyDischarges = false } = options;
  const results = [];
  
  // Extraer todos los HC únicos de esta semana primero
  const uniqueHcs = new Set();
  for (const [key] of Object.entries(weekData)) {
    const parts = key.split('_');
    const hc = parts[0];
    if (hc) uniqueHcs.add(String(hc));
  }
  
  // Cargar todos los discharges de una sola vez
  const dischargesByHc = await getDischargesByHc();
  
  // Usar allPatients que ya está en memoria (cargado por subscribeToPatientsData)
  // Esto evita hacer llamadas individuales a Firestore para cada paciente
  const activePatientsByHc = new Map();
  Object.values(allPatients).forEach(p => {
    if (p && p.hc) {
      activePatientsByHc.set(String(p.hc), p);
    }
  });
  
  for (const [key, dayData] of Object.entries(weekData)) {
    const parts = key.split('_');
    const hc = parts[0];
    const day = parts[1];
    if (!hc || !day || !DAYS.includes(day)) continue;
    
    // Buscar el paciente en Firestore
    let patientInfo = null;
    let isDischarged = false;
    
    // Primero buscar en pacientes activos (ya cargados en memoria via suscripción)
    const activePatient = activePatientsByHc.get(String(hc));
    if (activePatient) {
      patientInfo = activePatient;
      isDischarged = patientInfo.status === 'archived';
    } else {
      // Buscar en discharges
      const discharge = dischargesByHc.get(String(hc));
      if (discharge) {
        patientInfo = discharge;
        isDischarged = true;
      }
    }
    
    if (!patientInfo) continue;
    
    // Mostrar únicamente altas de la semana consultada
    if (!isDischarged || !isDischargeInWeek(patientInfo, weekId)) continue;
    
    results.push({
      wid: weekId,
      day,
      patient: patientInfo,
      hc,
      dayData,
      isDischarged,
      isDischargeInCurrentWeek: isDischarged && isDischargeInWeek(patientInfo, weekId),
      cama: patientInfo.cama || patientInfo.camaAnterior || '—' });
  }

  results.sort((a, b) => String(a.cama).localeCompare(String(b.cama)));
  return results;
}

