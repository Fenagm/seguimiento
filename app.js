function importPatients() {
  if (!pendingCSV.length) return;

  const incomingHCs = new Set(pendingCSV.map(p => String(p.hc)));
  const archivedPatients = [];

  // Archive active patients NOT in the new CSV
  for (const [hc, p] of Object.entries(allPatients)) {
    if (isPatientActive(p) && !incomingHCs.has(String(hc))) {
      allPatients[hc] = {
        ...p,
        status: PATIENT_STATUS.ARCHIVED,
        archivedAt: new Date().toISOString(),
        archivedReason: 'csv_import',
        archivedBy: getDisplayName(currentUser),
      };
      archivedPatients.push(p);
    }
  }

  // Upsert incoming patients
  for (const p of pendingCSV) {
    const existing = allPatients[p.hc];
    p.status = PATIENT_STATUS.ACTIVE;
    delete p.archivedAt;
    delete p.archivedReason;
    delete p.archivedBy;
    // Preserve week data link if patient already existed
    if (existing && existing.createdAt) p.createdAt = existing.createdAt;
    allPatients[p.hc] = p;
  }

  // Persistencia multiusuario: actualizar solo campos controlados por CSV para evitar pisar cambios concurrentes
  if (db) {
    const csvPatientMap = new Map(pendingCSV.map(p => [String(p.hc), p]));

    for (const [hc, p] of Object.entries(allPatients)) {
      if (csvPatientMap.has(String(hc))) {
        const csvPatient = csvPatientMap.get(String(hc));
        setDoc(doc(db, 'patients', hc), {
          hc: String(hc),
          cama: csvPatient.cama,
          paciente: csvPatient.paciente,
          medico: csvPatient.medico || '—',
          ingreso: csvPatient.ingreso || '—',
          cobertura: csvPatient.cobertura || '—',
          servicio: csvPatient.servicio || '—',
          diagnostico: csvPatient.diagnostico || 'SIN DIAGNÓSTICO',
          floor: csvPatient.floor,
          status: PATIENT_STATUS.ACTIVE,
          archivedAt: null,
          archivedReason: null,
          archivedBy: null,
        }, { merge: true }).catch(() => {});
      } else {
        setDoc(doc(db, 'patients', hc), {
          status: PATIENT_STATUS.ARCHIVED,
          archivedAt: p.archivedAt || new Date().toISOString(),
          archivedReason: p.archivedReason || 'csv_import',
          archivedBy: p.archivedBy || getDisplayName(currentUser),
        }, { merge: true }).catch(() => {});
      }
    }
  }

  const csvImportedAt = new Date().toISOString();
  localStorage.setItem('csvLastUploadAt', csvImportedAt);
  updateCSVLastUploadLegend(csvImportedAt);
  if (db) {
    setDoc(doc(db, 'meta', 'csv_import'), {
      lastUploadAt: serverTimestamp(),
      lastUploadBy: getDisplayName(currentUser),
      lastUploadByUid: currentUser?.uid || 'anonymous',
      importedCount: pendingCSV.length,
      archivedCount: archivedPatients.length,
    }, { merge: true }).catch(() => {});
  }

  saveAudit('csv_import', null, null, {
    imported: pendingCSV.length,
    archived: archivedPatients.length,
    archivedNames: archivedPatients.map(p => p.paciente),
  });

  closeCSV();
  renderTable();
  renderFloorTabs();

  const archiveMsg = archivedPatients.length
    ? ` · ${archivedPatients.length} archivado${archivedPatients.length !== 1 ? 's' : ''}`
    : '';
  showToast(`${pendingCSV.length} pacientes importados${archiveMsg} ✓`);
  pendingCSV = [];
}

