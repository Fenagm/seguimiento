function getMedicationSuggestions(catId, query) {
  if (!autocompleteEnabled) return [];
  const dict = MEDICATION_DICTIONARY[catId] || [];
  const q = String(query || '').trim().toLowerCase();
  if (!q) return dict.slice(0, 6);
  return dict.filter(item => item.toLowerCase().includes(q)).slice(0, 6);
}

function clearMedSuggestions(catId) {
  const list = document.getElementById(`med-list-${catId}`);
  if (list) list.innerHTML = '';
}

function renderMedSuggestions(catId, query) {
  const list = document.getElementById(`med-list-${catId}`);
  if (!list) return;
  const suggestions = getMedicationSuggestions(catId, query);
  if (!suggestions.length) {
    list.innerHTML = '';
    return;
  }
  list.innerHTML = suggestions.map(item => `
    <button type="button" class="med-suggestion-item" data-cat="${catId}" data-value="${item.replace(/"/g, '&quot;')}">${item}</button>
  `).join('');
  list.querySelectorAll('.med-suggestion-item').forEach(btn => {
    btn.addEventListener('click', () => applyMedicationSuggestion(catId, btn.dataset.value));
  });
}

function applyMedicationSuggestion(catId, value) {
  const med = String(value || '').trim();
  if (!med) return;
  const input = document.getElementById(`med-input-${catId}`);
  if (input) input.value = '';
  clearMedSuggestions(catId);
  const catTags = TAGS[catId] || [];
  const existingTagBtn = document.querySelector(`.tag-chip[data-cat="${catId}"][data-tag="${CSS.escape(med)}"]`);
  if (catTags.includes(med) && existingTagBtn && !existingTagBtn.classList.contains('active')) {
    toggleTag(catId, med, existingTagBtn);
    return;
  }
  const ta = document.getElementById(`ta-${catId}`);
  if (!ta) return;
  const sep = ta.value.trim() ? '; ' : '';
  ta.value = `${ta.value}${sep}${med}`;
  panelState.data[catId] = panelState.data[catId] || { tags: [], text: '' };
  panelState.data[catId].text = ta.value;
  updateCatSummary(catId);
}

function toggleCat(catId) {
  const body = document.getElementById(`cat-body-${catId}`);
  if (!body) return;
  const section = body.closest('.cat-section');
  const toggle = section?.querySelector('.cat-toggle');
  const isOpen = body.style.display !== 'none';
  const panelBody = document.getElementById('panel-body');

  if (isOpen) {
    body.style.display = 'none';
    if (toggle) toggle.textContent = '▾';
  } else {
    // UX: keep only one expanded category to avoid the panel growing too tall.
    document.querySelectorAll('.cat-body').forEach(otherBody => {
      if (otherBody.id === body.id) return;
      otherBody.style.display = 'none';
      const otherSection = otherBody.closest('.cat-section');
      const otherToggle = otherSection?.querySelector('.cat-toggle');
      if (otherToggle) otherToggle.textContent = '▾';
    });

    body.style.display = '';
    if (toggle) toggle.textContent = '▴';

    // Controlled scroll inside panel body to avoid abrupt viewport jumps.
    if (section && panelBody) {
      requestAnimationFrame(() => {
        const panelRect = panelBody.getBoundingClientRect();
        const sectionRect = section.getBoundingClientRect();
        const topGap = 12;
        const bottomGap = 18;
        const isAbove = sectionRect.top < panelRect.top + topGap;
        const isBelow = sectionRect.bottom > panelRect.bottom - bottomGap;

        if (isAbove || isBelow) {
          const delta = isAbove
            ? sectionRect.top - panelRect.top - topGap
            : sectionRect.bottom - panelRect.bottom + bottomGap;
          panelBody.scrollBy({ top: delta, behavior: 'smooth' });
        }
      });
    }
  }
}

function toggleTag(catId, tag, btn) {
  if (!panelState.data[catId]) panelState.data[catId] = { tags: [], text: '' };

  // Ensure tags is always an array
  if (!Array.isArray(panelState.data[catId].tags)) {
    panelState.data[catId].tags = [];
  }
  
  const tags = panelState.data[catId].tags;
  const textarea = document.getElementById(`ta-${catId}`);
  let currentText = textarea ? textarea.value : panelState.data[catId].text || '';

  const idx = tags.indexOf(tag);

  if (idx >= 0) {
    // Remover tag del array y del texto
    tags.splice(idx, 1);
    btn.classList.remove('active');
    // Remover el tag del texto si existe
    const tagRegex = tag.replace(/[.*+?^${}()|[\]\\]/g, '\\$&');
    const tagPattern = new RegExp('\\b' + tagRegex + '\\b', 'g');
    currentText = currentText.replace(tagPattern, '');
    currentText = currentText.replace(/,\s*,/g, ',').replace(/^,\s*|,\s*$/g, '').trim();
  } else {
    // Agregar tag al array y al texto
    tags.push(tag);
    btn.classList.add('active');
    // Agregar el tag al texto si no esta ya
    if (!currentText.includes(tag)) {
      currentText = currentText ? currentText + ', ' + tag : tag;
    }
  }

  panelState.data[catId].tags = tags;
  panelState.data[catId].text = currentText;

  if (textarea) textarea.value = currentText;
  updateCatSummary(catId);

  const body = document.getElementById(`cat-body-${catId}`);
  if (body && body.style.display === 'none') body.style.display = '';
}

